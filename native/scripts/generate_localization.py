#!/usr/bin/env python3
"""Embed a reviewed official .strings export; no runtime language download."""
import base64
import hashlib
import json
from pathlib import Path
import re

NATIVE = Path(__file__).resolve().parents[1]


def main():
    source = NATIVE / "Resources/ru.strings"
    text = source.read_text(encoding="utf-8")
    pairs = re.findall(r'"((?:[^"\\]|\\.)*)"\s*=\s*"((?:[^"\\]|\\.)*)"\s*;', text)
    # OpenStep .strings also escapes apostrophes and percent signs, unlike JSON.
    def decode(value):
        return json.loads('"' + value.replace("\\'", "'").replace("\\%", "%") + '"', strict=False)
    strings = {decode(k): decode(v) for k, v in pairs}
    assert len(strings) > 10000 and strings["Presence.online"] == "в сети"
    blob = base64.b64encode(json.dumps(strings, ensure_ascii=False, separators=(",", ":"), sort_keys=True).encode()).decode()
    output = '''// Generated by native/scripts/generate_localization.py. Do not edit.
// Official Telegram iOS Russian export, snapshot 2026-10-27.
// Source: https://translations.telegram.org/ru/ios/export
// SHA256: SOURCE_HASH
import Foundation

enum SimulatorLocalization {
    static func russian() -> LocalizationSettings {
        let encoded = """
ENCODED
"""
        let data = Data(base64Encoded: encoded, options: .ignoreUnknownCharacters)!
        let strings = try! JSONSerialization.jsonObject(with: data) as! [String: String]
        let suffixes = ["_0", "_1", "_2", "_3_10", "_many", "_any"]
        var simple: [String: String] = [:]
        var plural: [String: [String: String]] = [:]
        for (key, value) in strings {
            if let suffix = suffixes.first(where: { key.hasSuffix($0) }) {
                plural[String(key.dropLast(suffix.count)), default: [:]][suffix] = value
            } else {
                simple[key] = value
            }
        }
        var entries = simple.map { LocalizationEntry.string(key: $0.key, value: $0.value) }
        for (key, forms) in plural {
            entries.append(.pluralizedString(key: key, zero: forms["_0"], one: forms["_1"], two: forms["_2"], few: forms["_3_10"], many: forms["_many"], other: forms["_any"] ?? forms["_many"] ?? forms["_1"] ?? ""))
        }
        return LocalizationSettings(primaryComponent: LocalizationComponent(languageCode: "ru", localizedName: "Русский", localization: Localization(version: 0, entries: entries), customPluralizationCode: nil), secondaryComponent: nil)
    }
}
'''.replace("SOURCE_HASH", hashlib.sha256(source.read_bytes()).hexdigest()).replace("ENCODED", "\n".join(blob[i:i+120] for i in range(0, len(blob), 120)))
    (NATIVE / "Sources/Core/SimulatorLocalization.swift").write_text(output, encoding="utf-8", newline="\n")
    print(f"Embedded {len(strings)} original Russian translation keys")


if __name__ == "__main__":
    main()
